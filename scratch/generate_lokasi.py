import re
import json

lines = raw_text.strip().split("\n")
current_gedung = ""
rooms = []
id_counter = 1

for line in lines:
    line = line.strip()
    if line.startswith("Gedung"):
        current_gedung = line
        continue
    m = re.match(r'^\*\s+([A-Za-z0-9\.]+)\s+(.+)$', line)
    if m:
        kode = m.group(1).strip()
        nama = m.group(2).strip()
        rooms.append({
            'id': id_counter,
            'gedung': current_gedung,
            'kode_ruangan': kode,
            'nama': nama
        })
        id_counter += 1

print(f"Total parsed: {len(rooms)}")
with open("scratch/lokasi_parsed.json", "w", encoding="utf-8") as f:
    json.dump(rooms, f, indent=2)
